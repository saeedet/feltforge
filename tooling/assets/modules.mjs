import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
const root = resolve(import.meta.dirname, '../../packages/assets');
const manifest = JSON.parse(
  await readFile(resolve(root, 'manifest.json'), 'utf8'),
);
const records = new Map();
for (const a of manifest.assets) {
  const svg = await readFile(resolve(root, 'generated', a.path), 'utf8');
  records.set(a.path, { svg, width: a.width, height: a.height });
}
async function write(path, body) {
  const out = resolve(root, 'src/generated', path);
  await mkdir(dirname(out), { recursive: true });
  await writeFile(
    out,
    '// Generated by tooling/assets/modules.mjs. Do not edit.\n' + body,
  );
}
function inline(path) {
  const a = records.get(path);
  let body = a.svg
    .replace(
      /^<svg([^>]*)>/,
      (_, attrs) =>
        '<g' +
        attrs.replace(
          /\s(?:xmlns(?::xlink)?|viewBox|width|height|version)="[^"]*"/g,
          '',
        ) +
        '>',
    )
    .replace(/<\/svg>\s*$/, '</g>')
    .replaceAll('xlink:href', 'href');
  if (path === 'aces/spade.svg')
    body = body
      .replaceAll('#3b3c39', 'currentColor')
      .replaceAll('#fff', 'var(--card-ace-spade-inline, #fff)');
  if (path === 'backs/classic.svg')
    for (const [hex, name] of [
      ['#1f2a44', '--back-classic-field'],
      ['#b8955a', '--back-classic-gold'],
      ['#f2edc4', '--back-classic-ivory'],
      ['#f2f2f2', '--card-background'],
      ['#d2d5d9', '--card-border'],
    ])
      body = body.replaceAll(hex, `var(${name}, ${hex})`);
  return { body, viewBox: `0 0 ${a.width} ${a.height}` };
}

let symbols = 'import type {InlineAsset} from "../types.js";\n';
for (const [name, path] of [
  ['heart', 'suits/heart.svg'],
  ['diamond', 'suits/diamond.svg'],
  ['club', 'suits/club.svg'],
  ['spade', 'suits/spade.svg'],
  ['aceSpade', 'aces/spade.svg'],
  ...[
    'a',
    '2',
    '3',
    '4',
    '5',
    '6',
    '7',
    '8',
    '9',
    '10',
    'j',
    'q',
    'k',
    'joker',
  ].map((x) => ['rank' + x, 'ranks/' + x + '.svg']),
])
  symbols += `export const ${name}: InlineAsset = ${JSON.stringify(inline(path))};\n`;
await write('symbols.ts', symbols);
await write(
  'classic.ts',
  'import type {InlineAsset} from "../types.js";\nexport const classic: InlineAsset = ' +
    JSON.stringify(inline('backs/classic.svg')) +
    ';\n',
);
for (const style of ['persian', 'western', 'eastern'])
  await write(
    'courts/' + style + '.ts',
    'import type {CourtArtwork} from "../../types.js";\nexport const ' +
      style +
      ': CourtArtwork = ' +
      JSON.stringify({
        style,
        cards: Object.fromEntries(
          ['jack', 'queen', 'king'].map((r, i) => [
            ['J', 'Q', 'K'][i],
            inline(`courts/${style}/${r}.svg`),
          ]),
        ),
      }) +
      ';\n',
  );
for (const variant of ['1', '2'])
  await write(
    'jokers/' + variant + '.ts',
    'import type {JokerArtwork} from "../../types.js";\nexport const joker' +
      variant +
      ': JokerArtwork = ' +
      JSON.stringify({ variant, ...inline(`jokers/joker-${variant}.svg`) }) +
      ';\n',
  );
console.log('Generated independently importable artwork modules.');
