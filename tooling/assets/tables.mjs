import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { optimize } from 'svgo';
import { format, resolveConfig } from 'prettier';

const root = resolve(import.meta.dirname, '../..');
const specification = JSON.parse(
  await readFile(
    resolve(root, 'docs/design/table-theme-specification.json'),
    'utf8',
  ),
);
const skins = {};
async function prepare(layer) {
  const output = { ...layer };
  delete output.sourceId;
  if (output.asset) {
    const source = await readFile(
      resolve(root, 'tooling/assets/source/table-wordmarks', output.asset),
      'utf8',
    );
    if (
      /<(?:text|image|foreignObject)\b|@font-face|data:|https?:\/\/(?!www.w3.org)/i.test(
        source,
      )
    )
      throw Error('Table lettering must contain only local vector outlines');
    const svg = optimize(source, {
      plugins: ['preset-default', 'removeDimensions'],
      floatPrecision: 5,
    }).data;
    output.wordmark = {
      viewBox: svg.match(/viewBox="([^"]+)"/)[1],
      body: svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, ''),
    };
    delete output.asset;
  }
  if (output.children)
    output.children = await Promise.all(output.children.map(prepare));
  return output;
}
for (const master of specification.masters)
  skins[master.theme] = await Promise.all(master.layers.map(prepare));
const target = resolve(root, 'packages/react/src/table-skins.generated.ts');
await writeFile(
  target,
  await format(
    `// Generated by pnpm generate:tables from the captured Penpot masters.\nimport type { TableTheme } from '@feltforge/core';\nimport type { TableLayer } from './table-skin-types.js';\nexport const TABLE_SKINS: Readonly<Record<TableTheme, readonly TableLayer[]>> = ${JSON.stringify(skins, null, 2)};\n`,
    { ...(await resolveConfig(target)), parser: 'typescript' },
  ),
);
console.log('Prepared six vector table skins and outlined lettering.');
